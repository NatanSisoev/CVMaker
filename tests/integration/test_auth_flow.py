def test_failed_logins_lock_the_account_briefly(client, verified_user):
    """allauth enforces ``login_failed`` in the form: after 5 failures even the
    right password is refused (with a message), so guessing can't continue."""
    url = reverse("account_login")
    for _ in range(5):
        client.post(url, {"login": verified_user.email, "password": "wrong"})

    resp = client.post(url, {"login": verified_user.email, "password": PASSWORD})

    assert resp.status_code == 200
    assert b"Too many failed login attempts" in resp.content
    assert client.get(reverse("cv-list")).status_code == 302  # not logged in


def test_signups_are_limited_per_ip(client):
    url = reverse("account_signup")
    for i in range(5):
        client.post(
            url, {"email": f"s{i}@example.com", "password1": PASSWORD, "password2": PASSWORD}
        )
    resp = client.post(
        url, {"email": "late@example.com", "password1": PASSWORD, "password2": PASSWORD}
    )
    assert resp.status_code == 429
    assert not User.objects.filter(email="late@example.com").exists()
