"""Auth via django-allauth (Phase 6): email identity, mandatory verification,
password reset, 2FA pages, and allauth's own rate limits."""

from __future__ import annotations

import re

import pytest
from allauth.account.models import EmailAddress
from django.contrib.auth import get_user_model
from django.core import mail
from django.urls import reverse

User = get_user_model()
pytestmark = pytest.mark.django_db
PASSWORD = "pbkdf2-dev-only-password"


@pytest.fixture
def verified_user(user):
    user.set_password(PASSWORD)
    user.save()
    EmailAddress.objects.create(user=user, email=user.email, verified=True, primary=True)
    return user


def _link(message) -> str:
    return re.search(r"https?://[^/]+(/\S+)", message.body).group(1)


def test_signup_sends_verification_and_confirming_logs_in(client):
    resp = client.post(
        reverse("account_signup"),
        {"email": "New.User@Example.com", "password1": PASSWORD, "password2": PASSWORD},
    )
    assert resp.status_code == 302
    assert resp.url == reverse("account_email_verification_sent")

    user = User.objects.get(email__iexact="new.user@example.com")
    assert user.username  # generated by allauth
    assert not EmailAddress.objects.get(user=user).verified

    (message,) = mail.outbox
    assert message.subject.startswith("[CVMaker] ")
    confirm_url = _link(message)

    # GET shows a confirm button (link scanners can't verify); POST verifies.
    page = client.get(confirm_url)
    assert page.status_code == 200 and b"<form" in page.content
    done = client.post(confirm_url)
    assert done.status_code == 302
    assert EmailAddress.objects.get(user=user).verified
    assert client.get(reverse("cv-list")).status_code == 200  # logged in


def test_unverified_user_cannot_log_in(client, user):
    user.set_password(PASSWORD)
    user.save()
    EmailAddress.objects.create(user=user, email=user.email, verified=False, primary=True)

    resp = client.post(reverse("account_login"), {"login": user.email, "password": PASSWORD})

    assert resp.status_code == 302
    assert resp.url == reverse("account_email_verification_sent")
    assert client.get(reverse("cv-list")).status_code == 302  # still anonymous


def test_verified_user_logs_in_with_email_case_insensitively(client, verified_user):
    resp = client.post(
        reverse("account_login"), {"login": verified_user.email.upper(), "password": PASSWORD}
    )
    assert resp.status_code == 302 and resp.url == "/"
    assert client.get(reverse("cv-list")).status_code == 200


def test_wrong_password_rerenders_login(client, verified_user):
    resp = client.post(reverse("account_login"), {"login": verified_user.email, "password": "no"})
    assert resp.status_code == 200
    assert b"text-danger" in resp.content or b'role="alert"' in resp.content


def test_password_reset_sends_a_working_link(client, verified_user):
    client.post(reverse("account_reset_password"), {"email": verified_user.email})
    (message,) = mail.outbox
    reset_page = client.get(_link(message), follow=True)
    assert reset_page.status_code == 200
    assert b'name="password1"' in reset_page.content


def test_logout_requires_post(client, verified_user):
    client.force_login(verified_user)
    client.get(reverse("account_logout"))  # GET shows a confirmation, doesn't log out
    assert client.get(reverse("cv-list")).status_code == 200
    client.post(reverse("account_logout"))
    assert client.get(reverse("cv-list")).status_code == 302


@pytest.mark.parametrize(
    "name",
    ["account_login", "account_signup", "account_reset_password"],
)
def test_entrance_pages_use_the_design_system(client, name):
    body = client.get(reverse(name)).content.decode()
    assert 'class="cv-form' in body  # our form element override
    assert "font-display" in body  # our heading element override
    assert "dist/app.css" in body  # rendered inside base.html


def test_two_factor_page_renders_for_signed_in_users(client, verified_user):
    client.force_login(verified_user)
    resp = client.get(reverse("mfa_index"))
    assert resp.status_code == 200
    assert b"Two-factor" in resp.content  # manage-layout nav


